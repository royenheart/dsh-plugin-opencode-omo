#!/usr/bin/env node
/**
 * Generate `cordis.patch.yml` from `cordis.patch.template.yml` plus the
 * opencode-omo preset composition.
 *
 * Official 0.1.7 presets are `@deepseek-ai/dsh-agent-preset` declaration rows
 * carried by a bundle/profile patch; the former `$DSH_HOME/.agent-presets`
 * directory root is no longer read. The composition stays the single source of
 * truth in `presets/opencode-omo/agent.cordis.yml`; this generator nests it as
 * the declaration's `config.plugins` and rewrites the preset-relative module
 * rows (`./driver.mjs`) to package subpaths the loader can resolve from the
 * profile.
 *
 * Textual transformation on purpose: the composition uses the loader's `!!js`
 * expression tag, which a generic YAML parse would not round-trip.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PACKAGE = '@royenheart/dsh-plugin-opencode-omo'
const PRESET_DIR = 'presets/opencode-omo'

/** Read one top-level scalar from the preset's display metadata. */
function presetField(source, name) {
  return source.match(new RegExp(`^${name}:\\s*(.+)$`, 'm'))?.[1]?.trim() ?? ''
}

const template = readFileSync(join(ROOT, 'cordis.patch.template.yml'), 'utf8').trimEnd()
const metadata = readFileSync(join(ROOT, PRESET_DIR, 'preset.yml'), 'utf8')
const composition = readFileSync(join(ROOT, PRESET_DIR, 'agent.cordis.yml'), 'utf8')
  .trimEnd()
  // `./driver.mjs` in the preset directory becomes a quoted package subpath so
  // the loader resolves it through the linked bundle instead of the profile
  // cwd. `@` cannot begin a YAML plain scalar.
  .replace(/^(\s*name:\s*)\.\/(\S+)\s*$/gm, `$1'${PACKAGE}/${PRESET_DIR}/$2'`)

const plugins = composition
  .split('\n')
  .map(line => (line.trim() === '' ? line : `        ${line}`))
  .join('\n')

const document = `# GENERATED by scripts/build-preset-patch.mjs — do not edit.
# Sources: cordis.patch.template.yml + presets/opencode-omo/{preset.yml,agent.cordis.yml}
${template}

- insert:
    - id: preset-opencode-omo
      # Headless-safe wrapper around the official declaration row: it keeps the
      # same config shape and EntryGroup semantics, but activates without the
      # preset registry and registers through agentPresets once it exists, so a
      # headless composition (dsh-base + dsh-headless) has no pending entry.
      # See presets/opencode-omo/preset-row.mjs.
      name: '${PACKAGE}/${PRESET_DIR}/preset-row.mjs'
      config:
        id: ${presetField(metadata, 'name')}
        order: ${presetField(metadata, 'order') || '5'}
        description: ${JSON.stringify(presetField(metadata, 'description'))}
        plugins:
${plugins}
`

writeFileSync(join(ROOT, 'cordis.patch.yml'), document)
console.log(`generated cordis.patch.yml (${String(document.split('\n').length)} lines)`)
